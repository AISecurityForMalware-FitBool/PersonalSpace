def sniff_split(path: str) -> str:
    """
    경로 세그먼트가 'train', 'val(valid/validation)', 'test(testing)'로
    '시작'만 해도 인식하도록 완화. (예: Train_420 -> train)
    """
    p = path.lower().replace("\\", "/")
    parts = [seg for seg in p.split("/") if seg]
    for comp in reversed(parts):
        c = comp.strip()
        if c in ("train",):
            return "train"
        if c in ("val", "valid", "validation"):
            return "val"
        if c in ("test", "testing"):
            return "test"
        if c.startswith("train"):
            return "train"
        if c.startswith(("val", "valid", "validation")):
            return "val"
        if c.startswith(("test", "testing")):
            return "test"
    return ""


def sniff_label(path: str) -> Tuple[int, str]:
    p = path.lower()
    if "malware" in p:
        return 1, "malware"
    if "normal" in p or "benign" in p or "clean" in p:
        return 0, "normal"
    return -1, ""


def is_hidden_name(name: str) -> bool:
    base = os.path.basename(name)
    return any(base.startswith(pref) for pref in HIDDEN_NAME_PREFIXES)


def file_sha256(path: str, buf=1024*1024) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            b = f.read(buf)
            if not b: break
            h.update(b)
    return h.hexdigest()


def entropy_bytes(data: bytes) -> float:
    if not data:
        return -1.0
    counts = [0]*256
    for b in data:
        counts[b] += 1
    total = len(data)
    ent = 0.0
    for c in counts:
        if c:
            p = c/total
            ent -= p*math.log2(p)
    return ent


def entropy_of_file(path: str, max_bytes=MAX_BYTES_FOR_ENTROPY) -> float:
    size = os.path.getsize(path)
    to_read = size if (max_bytes is None) else min(size, max_bytes)  # ✅ 전체 사용 or 상한
    if to_read <= 0:
        return -1.0
    read = 0
    counts = [0]*256
    with open(path, "rb") as f:
        while read < to_read:
            chunk = f.read(min(1024*1024, to_read - read))  # 1MB 스트리밍
            if not chunk:
                break
            read += len(chunk)
            for b in chunk:
                counts[b] += 1
    if read == 0:
        return -1.0
    ent = 0.0
    for c in counts:
        if c:
            p = c/read
            ent -= p*math.log2(p)
    return ent


def parse_pe_and_sections(path: str, max_section_bytes=2*1024*1024):
    """
    강화된 PE 파서:
    - MZ/PE 확인
    - PE32/PE32+ Magic
    - Characteristics로 DLL 여부
    - SizeOfHeaders/섹션 포인터 정합성
    - 섹션 포인터 범위/겹침
    - 섹션 엔트로피/패커 섹션명 힌트
    """
    info = dict(
        pe_valid=False, machine=-1, num_sections=-1, magic=-1,
        characteristics=0, is_dll=0, size_of_headers=-1,
        pointer_sanity_ok=0, ptr_oob_sections=0, overlap_sections=0,
        section_entropy_mean=-1.0, section_entropy_max=-1.0, high_entropy_sections=0,
        packer_name_hint="", packer_name_hit=0
    )
    try:
        fsz = os.path.getsize(path)
        with open(path, "rb") as f:
            if f.read(2) != b"MZ":
                return info
            f.seek(0x3C)
            pe_off_b = f.read(4)
            if len(pe_off_b) < 4:
                return info
            pe_off = int.from_bytes(pe_off_b, "little", signed=False)
            f.seek(pe_off)
            if f.read(4) != b"PE\x00\x00":
                return info

            # COFF
            coff = f.read(20)
            if len(coff) < 20:
                return info
            (machine, num_sections, _ts, _ptrsym, _numsym, size_opt, characteristics) = struct.unpack("<HHIIIHH", coff)
            info["machine"] = machine
            info["num_sections"] = num_sections
            info["characteristics"] = characteristics
            info["is_dll"] = 1 if (characteristics & 0x2000) else 0  # IMAGE_FILE_DLL

            # Optional header
            opt_pos = f.tell()
            magic = struct.unpack("<H", f.read(2))[0]
            info["magic"] = magic
            # SizeOfHeaders: +0x3C
            f.seek(opt_pos + 0x3C)
            soh_b = f.read(4)
            if len(soh_b) == 4:
                info["size_of_headers"] = int.from_bytes(soh_b, "little", signed=False)
            f.seek(opt_pos + size_opt)  # 섹션 테이블로

            ranges = []
            section_ents = []
            packer_hit = ""
            first_ptr = None

            for _ in range(num_sections):
                sh = f.read(40)
                if len(sh) < 40:
                    break
                name, vsize, vaddr, size_raw, ptr_raw, *_ = struct.unpack("<8sIIIIIIHHI", sh)
                up = name.strip(b"\x00")
                if any(h in up for h in PACKER_HINT_NAMES):
                    packer_hit = up.decode(errors="ignore")

                if size_raw > 0 and ptr_raw > 0:
                    if first_ptr is None or ptr_raw < first_ptr:
                        first_ptr = ptr_raw
                    end = ptr_raw + size_raw
                    ranges.append((ptr_raw, end))
                    # 섹션 엔트로피
                    try:
                        with open(path, "rb") as sf:
                            sf.seek(ptr_raw)
                            data = sf.read(min(size_raw, max_section_bytes))
                            ent = entropy_bytes(data)
                            if ent >= 0:
                                section_ents.append(ent)
                    except:
                        pass

            # 범위/겹침 검증
            ptr_oob = 0
            for s, e in ranges:
                if s < 0 or e < 0 or s > fsz or e > fsz or s >= e:
                    ptr_oob += 1
            info["ptr_oob_sections"] = ptr_oob

            overlap = 0
            rs = sorted(ranges)
            for i in range(1, len(rs)):
                ps, pe = rs[i-1]
                cs, ce = rs[i]
                if cs < pe:
                    overlap += 1
            info["overlap_sections"] = overlap

            if info["size_of_headers"] > 0 and (first_ptr is not None):
                info["pointer_sanity_ok"] = 1 if first_ptr >= info["size_of_headers"] else 0

            if section_ents:
                info["section_entropy_mean"] = sum(section_ents)/len(section_ents)
                info["section_entropy_max"]  = max(section_ents)
                info["high_entropy_sections"] = sum(1 for e in section_ents if e >= HIGH_ENTROPY_THRESH)

            if packer_hit:
                info["packer_name_hint"] = packer_hit
                info["packer_name_hit"]  = 1

            info["pe_valid"] = True
            return info
    except:
        return info


def ensure_dir(p: str):
    os.makedirs(p, exist_ok=True)


def pct(x, n):
    return 0.0 if n == 0 else round(100.0 * x / n, 1)


def materialize_clean_set(rows, clean_root: str):
    """eligible 행을 기준으로 정제본 EXE 복사본 생성."""
    if not clean_root:
        return 0, 0

    ensure_dir(clean_root)

    # 누수 제거(동일 sha가 여러 split에 있으면 하나만 선택)
    selected = []
    if ENFORCE_NO_LEAKS:
        by_sha = defaultdict(list)
        for r in rows:
            if r["eligible"] == 1 and r["sha256"]:
                by_sha[r["sha256"]].append(r)

        for sha, items in by_sha.items():
            if len(items) == 1:
                selected.append(items[0])
            else:
                # 우선순위 split 선택
                best = None
                for sp in SPLIT_PRIORITY + [""]:
                    cand = [x for x in items if (x["split"] or "") == sp]
                    if cand:
                        best = cand[0]; break
                selected.append(best)
    else:
        selected = [r for r in rows if r["eligible"] == 1]

    copied, errors = 0, 0
    for r in selected:
        try:
            src = r["path"]
            if not os.path.isfile(src):
                continue

            # 대상 디렉토리
            split = r["split"] or "unsplit"
            label = r["label_name"] or ("label_"+str(r["label"]))
            if PRESERVE_STRUCTURE:
                dst_dir = os.path.join(clean_root, split, label)
            else:
                dst_dir = os.path.join(clean_root, label)
            ensure_dir(dst_dir)

            # 파일명
            if RENAME_BY_SHA and r["sha256"]:
                stem = r["sha256"]
                fname = stem + RENAME_EXT
            else:
                fname = os.path.basename(src)

            dst = os.path.join(dst_dir, fname)
            # 충돌 방지
            base, ext = os.path.splitext(dst)
            i = 1
            while os.path.exists(dst):
                dst = f"{base}_{i}{ext}"
                i += 1

            shutil.copy2(src, dst)
            copied += 1
        except Exception as e:
            errors += 1
            print(f"[복사 에러] {r.get('path','<unknown>')} -> {dst_dir} ({e})")

    return copied, errors


